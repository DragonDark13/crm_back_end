"""Integration tests for API authentication and role-based authorization.

The application performs database initialization during import. These tests
prepare a small SQLite database containing only the authentication tables
before importing app.py, so no production PostgreSQL database is required.
"""
import importlib
import os
import tempfile
from pathlib import Path

import pytest
from sqlalchemy import create_engine

# Configure the test database before importing the application.
_db_fd, _db_path = tempfile.mkstemp(prefix="crm-auth-tests-", suffix=".sqlite3")
os.close(_db_fd)
os.environ["DATABASE_URL"] = f"sqlite:///{Path(_db_path).as_posix()}"
os.environ["SECRET_KEY"] = "integration-test-secret-key"
os.environ["JWT_SECRET_KEY"] = "integration-test-jwt-secret"
os.environ["GUEST_PASSWORD"] = "guest-test-password"
os.environ["MANAGER_PASSWORD"] = "manager-test-password"

# Importing models registers the ORM tables. Create only the tables required
# by app.py's import-time role/user initialization and JWT authorization.
from models import db, User, Role, TokenBlocklist, LoginAttempt, LoginIPAttempt
from models.associations import user_roles_table

_engine = create_engine(os.environ["DATABASE_URL"])
db.metadata.create_all(
    bind=_engine,
    tables=[
        Role.__table__,
        User.__table__,
        user_roles_table,
        TokenBlocklist.__table__,
        LoginAttempt.__table__,
        LoginIPAttempt.__table__,
    ],
)
_engine.dispose()

app_module = importlib.import_module("app")
app = app_module.app



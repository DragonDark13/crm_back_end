def test_guest_cannot_perform_write_operations(client, auth_tokens, monkeypatch):
    monkeypatch.setitem(
        app.view_functions,
        "create_and_purchase_product",
        lambda: ("created", 201),
    )
    response = client.post(
        "/api/add_new_product",
        json={"name": "authorization-test"},
        headers=_auth_headers(auth_tokens["guest"]),
    )
    assert response.status_code == 403



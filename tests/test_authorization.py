def _auth_headers(token):
    return {"Authorization": f"Bearer {token}"}


@pytest.mark.parametrize(
    "path",
    [
        "/api/get_all_sales_history",
        "/api/get_all_purchase_history",
        "/api/statistics/sales/monthly",
        "/api/statistics/profit-expense",
        "/api/investments/get_all_investments",
    ],
)
def test_guest_can_read_financial_get_endpoints(client, auth_tokens, stub_financial_get_views, path):
    response = client.get(path, headers=_auth_headers(auth_tokens["guest"]))
    assert response.status_code == 200


